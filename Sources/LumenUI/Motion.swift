import SwiftUI

/// Общие движения интерфейса (Рома, 25.10: панели и страницы — плавно, а не рывком).
/// Пружины без отскока: начинаются быстро и мягко садятся; одна длительность на всё приложение.
enum Motion {
    /// Боковые панели (левая, браузер), настройки поверх окна
    static let panel = Animation.smooth(duration: 0.32)
    /// Смена страницы: чат, кастомизация, память, артефакты…
    static let page = Animation.smooth(duration: 0.26)
}
