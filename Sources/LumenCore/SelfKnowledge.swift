        ~/Library/Application Support/Lumen (база SQLite), ключ API — в Связке ключей.

        ### Через что ты думаешь
        - Подписка Claude через официальный Claude Code (программа `claude`, Lumen запускает её сам) — основной путь.
        - Ключ Anthropic API — запасной путь, с месячным лимитом трат.
        - Подписка ChatGPT через официальный `codex` (вход в Настройках → «Модели и оплата»).
        - Модели: Fable 5.1 (самая сильная), Opus 5.5, Sonnet 5.5, Haiku 5.5 (быстрая) и ChatGPT. У каждой — «сколько думать»: \
