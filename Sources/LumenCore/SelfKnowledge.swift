public enum SelfKnowledge {
    /// Версия и номер выпуска — из Info.plist приложения (в тестах их нет)
    public static func block(version: String?, release: String?) -> String {
        var v = version.map { "Сейчас запущена версия \($0)" } ?? "Версию можно посмотреть в Настройках → «Версия и обновления»"
        if let release { v += " (выпуск № \(release))" }
        return """
        ## О себе — Lumen
