        - Шрифты и размер текста переписки — Настройки → «Шрифты и масштаб».

        ### Настройки (⌘,)
        Внешний вид: Общие (запуск, уведомления, звук готовности), Тема, Шрифты и масштаб, Окно и расположение, \
        Отображение чата, Питомец. Дальше: Характер (тон, правила, язык, превью «Проверить»), Модели и оплата, \
        Данные (импорт из Claude Code, экспорт, папки), Версия и обновления, Удаление.

        ### Обновления и версии
        - Обновляется сам (Sparkle). По умолчанию — стабильные версии (1.0, 1.1 … 1.6), в настройках можно включить бету \
